import { execFileSync } from 'node:child_process'
import { readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs'
import { dirname, join, relative, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '../..')
const sourceDir = join(root, 'resources/js')
const mdiCss = join(root, 'node_modules/@mdi/font/css/materialdesignicons.css')
const mdiTtf = join(root, 'node_modules/@mdi/font/fonts/materialdesignicons-webfont.ttf')
const outFont = join(root, 'resources/fonts/mdi-icons.woff2')
const outCss = join(root, 'resources/css/mdi-icons.css')

const ICON_PATTERN = /mdi-[a-z0-9]+(?:-[a-z0-9]+)*/g

function collectFiles(dir) {
    return readdirSync(dir).flatMap((entry) => {
        const full = join(dir, entry)

        if (statSync(full).isDirectory()) {
            return collectFiles(full)
        }

        return /\.(vue|js)$/.test(entry) ? [full] : []
    })
}

function usedIcons() {
    const found = new Set()

    for (const file of collectFiles(sourceDir)) {
        // Drop import lines first: a path such as "../css/mdi-icons.css"
        // would otherwise read as an icon named "mdi-icons".
        const source = readFileSync(file, 'utf8').replace(/^import\s[^\n]*$/gm, '')

        for (const match of source.matchAll(ICON_PATTERN)) {
            found.add(match[0])
        }
    }

    return [...found].sort()
}

function parseIconMap(css) {
    const map = new Map()
    const pattern = /\.mdi-([a-z0-9-]+)::before\s*\{\s*content:\s*"\\([0-9A-Fa-f]+)"/g

    for (const [, name, hex] of css.matchAll(pattern)) {
        map.set(`mdi-${name}`, Number.parseInt(hex, 16))
    }

    return map
}

function parseBaseRule(css) {
    const match = css.match(/\.mdi:before,\s*\.mdi-set\s*\{[^}]+\}/)

    if (!match) {
        throw new Error('Could not find the .mdi base rule in the MDI stylesheet.')
    }

    return match[0]
}

const icons = usedIcons()

if (icons.length === 0) {
    throw new Error('No mdi-* icons found in resources/js. Refusing to write an empty subset.')
}

const css = readFileSync(mdiCss, 'utf8')
const map = parseIconMap(css)
const missing = icons.filter((icon) => !map.has(icon))

if (missing.length > 0) {
    throw new Error(`Unknown MDI icons (not in ${relative(root, mdiCss)}):\n  ${missing.join('\n  ')}`)
}

const unicodes = icons.map((icon) => `U+${map.get(icon).toString(16).toUpperCase()}`).join(',')

execFileSync('python', [
    '-m', 'fontTools.subset', mdiTtf,
    `--unicodes=${unicodes}`,
    '--flavor=woff2',
    '--layout-features=',
    '--no-hinting',
    '--desubroutinize',
    '--name-IDs=',
    '--output-file=' + outFont,
], { stdio: 'inherit' })

const rules = icons
    .map((icon) => `.${icon}::before {\n  content: "\\${map.get(icon).toString(16).toUpperCase()}";\n}`)
    .join('\n\n')

writeFileSync(outCss, `/*
 * Generated by "npm run icons:subset" - do not edit by hand.
 * Carries only the ${icons.length} Material Design Icons glyphs this app uses,
 * which keeps the icon font small enough to load on a mobile connection.
 */
@font-face {
    font-family: 'Material Design Icons';
    src: url('../fonts/mdi-icons.woff2') format('woff2');
    font-weight: 400;
    font-style: normal;
    font-display: block;
}

${parseBaseRule(css)}

${rules}
`)

const size = statSync(outFont).size

console.log(`icons:subset  ${icons.length} glyphs, ${(size / 1024).toFixed(1)} kB woff2`)
console.log(`              ${relative(root, outCss)}`)
